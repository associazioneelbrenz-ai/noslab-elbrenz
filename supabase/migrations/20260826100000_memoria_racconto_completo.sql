<h2>Erano di casa, e venivano da mille chilometri</h2>

<p class="capolettera">Il 26 maggio 1918 muoiono a Malè due uomini nello stesso giorno. Si chiamano
Leo Herdliczka e Johann Zahalka, sono tutti e due tenenti, e appartengono tutti e due alla 73ª
squadriglia aerea. Uno è nato a Mistek, in Slesia; l'altro a Tobitschan, in Moravia. Il registro
non dice altro, ma due uomini della stessa squadriglia che muoiono nello stesso giorno erano
quasi certamente sullo stesso aereo: il pilota e il suo osservatore, che volavano sopra queste
montagne e non sono più tornati.</p>

<p>Sono due delle centodiciotto righe di un registro che per centosette anni è rimasto chiuso in
un cartone dell'Archivio di Stato austriaco, a Vienna. Sei colonne, scritte a mano da un
impiegato militare: numero della tomba, grado, nome, reparto, giorno della morte, luogo di
nascita.</p>

<p>È l'ultima colonna quella che spiazza. Non dice Malè, non dice Trento, non dice Tirolo. Dice
Mistek, dice Tobitschan, dice Lemberg, dice Sarajevo.</p>

<h3>Un paese molto più grande di come ce lo immaginiamo</h3>

<p>Fino al 1920 le nostre valli non erano la periferia settentrionale dell'Italia. Erano una valle
interna di un paese che andava dal lago di Garda ai Carpazi, e che comprendeva quelli che oggi
chiamiamo Austria, Ungheria, Repubblica Ceca, Slovacchia, Slovenia, Croazia, Bosnia, e ampie
porzioni di Polonia, Ucraina e Romania.</p>

<p>Chi nasceva a Malè, a Cles o a Pejo nasceva cittadino di quel paese. Aveva la stessa moneta di
un tipografo di Praga, lo stesso passaporto di un contadino della Galizia, lo stesso imperatore
di un pescatore dalmata. Partendo per il servizio militare poteva finire in un reggimento con
ragazzi che non parlavano una parola della sua lingua, e la cosa era del tutto normale.</p>

<p class="rilievo">Questo cambia il senso di quelle centodiciotto righe. Quegli uomini non erano
stranieri morti nelle nostre valli. <b>Erano concittadini morti a casa propria</b>, in una parte
del loro paese che non avevano mai visto prima.</p>

<h3>Il conto delle distanze</h3>

<p>Se da Malè si tira una linea verso ogni luogo di nascita scritto nel registro, viene fuori la
mappa di quel paese scomparso.</p>

<ul class="distanze">
  <li><b>1150 km</b><span>Czernowitz, in Bucovina. Oggi Chernivtsi, in Ucraina.</span></li>
  <li><b>1050 km</b><span>Lemberg, capitale della Galizia. Oggi Leopoli, in Ucraina.</span></li>
  <li><b>780 km</b><span>Cracovia, oggi in Polonia.</span></li>
  <li><b>650 km</b><span>Sarajevo, in Bosnia.</span></li>
  <li><b>630 km</b><span>Budapest, in Ungheria.</span></li>
  <li><b>490 km</b><span>Praga, in Boemia.</span></li>
  <li><b>350 km</b><span>Graz, in Stiria: da sola, ventuno uomini su centodiciotto.</span></li>
</ul>

<p>Undici erano nati in Galizia, la provincia più orientale e più povera dell'impero, oggi divisa
fra la Polonia sudorientale e l'Ucraina occidentale. Uno veniva dalla Bucovina, che oggi sta fra
Ucraina e Romania. Ragazzi partiti da villaggi di terra battuta a milleduecento chilometri da
qui, arrivati sotto queste montagne per non ripartire più.</p>

<p>E poi c'è Josef Höllbling, Kaiserjäger del secondo reggimento, nato nel 1871 a <b>Nauders</b>,
all'estremo nord del Tirolo, sopra Resia. Uno dei pochissimi tirolesi dell'elenco. Aveva
quarantacinque anni e nella lista è il più anziano di tutti.</p>

<h3>Chi erano, reparto per reparto</h3>

<p>Nel registro compaiono <b>cinquantacinque reparti diversi</b>. Non è un cimitero di una
divisione: è il punto in cui una valle di retrovia raccoglieva quello che il fronte mandava
indietro, da mezzo esercito.</p>

<h4>Il 26° Schützen, ventidue uomini</h4>

<p>È il reparto più presente. Ventidue dei centodiciotto, e le loro terre di nascita dicono
tutte la stessa cosa: Stiria, Carinzia, Carniola, e qualcuno dalla Bassa Austria, dalla Slesia
e dalla Bosnia. Erano uomini di montagna reclutati sul versante orientale delle Alpi, il tipo
di truppa che si mandava dove le strade finiscono.</p>

<p>I loro morti si concentrano fra luglio e ottobre del 1918: sono lì fino alla fine.</p>

<h4>Kaiserjäger e Kaiserschützen: i reparti dei nostri</h4>

<p>Qui la faccenda diventa personale, e vale la pena spiegarla per bene.</p>

<p>Un ragazzo delle Valli del Noce che veniva chiamato alle armi tirava a sorte, e i nostri
bisnonni chiamavano quel sorteggio <i>nar en la cava</i>. Se usciva l'esercito comune finiva
quasi sempre nei <b>Tiroler Kaiserjäger</b>, i cacciatori imperiali, quattro reggimenti con sede
a Trento e Innsbruck, Bolzano e Bressanone, Rovereto, Bregenz e Riva del Garda. Se usciva la
Landwehr finiva nei <b>Landesschützen</b>, i fucilieri del Paese, reclutati soltanto in Tirolo,
di lingua tedesca e di lingua italiana. Nel gennaio del 1917 l'imperatore Carlo li nominò
<b>Kaiserschützen</b>, a Calliano, davanti al fronte trentino, come riconoscimento per come si
erano battuti.</p>

<p>Nel registro di Malè ce ne sono dieci: sei Kaiserschützen e quattro Kaiserjäger.</p>

<p>E i tre uomini del 2° reggimento Kaiserjäger sono <b>gli unici tirolesi di tutto l'elenco</b>.
Fra loro Josef Höllbling di Nauders, il più anziano dei centodiciotto.</p>

<p class="rilievo">Nessun trentino, però. Non uno. E non è un caso: quando nel 1916 Kaiserjäger e
Kaiserschützen furono riportati sul fronte italiano, <b>gli italofoni ne vennero tolti</b> e
riuniti nei battaglioni del sud-ovest, mandati a combattere sul fronte orientale. Non li si
voleva davanti al Regno d'Italia.</p>

<p>È il rovesciamento di tutta questa storia. Nel cimitero militare del loro paese, i nostri
bisnonni non ci sono, perché li avevano mandati a milleduecento chilometri da casa. E al loro
posto, sotto il campanile di Malè, riposano i ragazzi che erano partiti da quei milleduecento
chilometri.</p>

<h4>L'artiglieria da montagna, dodici uomini</h4>

<p>Il 1°, il 12°, il 22° e il 122° reggimento di artiglieria da montagna. Erano quelli che
portavano i pezzi smontati a dorso di mulo dove nessun cannone da campagna sarebbe mai arrivato,
e li rimontavano sopra i duemila metri. Fra loro Martin Gailberger, il carinziano del 1899 morto
il 20 ottobre 1918.</p>

<p>Con loro c'è anche l'artiglieria da campagna e da fortezza, altri dodici uomini sparsi in nove
reggimenti diversi, fino al 2° reggimento artiglieria da fortezza, dove servì un uomo nato in
Bucovina, l'estremo confine orientale dell'impero.</p>

<h4>I Landsturm, gli uomini che non erano più ragazzi</h4>

<p>Il Landsturm era l'ultima riserva: uomini oltre l'età della leva, richiamati quando i giovani
non bastavano più. Nel registro sono sette, fra battaglioni e compagnie territoriali, e sono
anche <b>i primi a morire</b>: la 23ª compagnia Landsturm perde tre uomini di Hallein, in
Salisburgo, fra il dicembre 1914 e l'aprile 1915, quando la guerra su questo fronte era appena
cominciata.</p>

<p>Fra loro Julius Hampl, moravo, nato nel 1873: aveva quarantacinque anni.</p>

<h4>Quelli che non sparavano</h4>

<p>Il registro conserva anche chi la guerra la faceva con le mani. Due battaglioni di zappatori,
due del treno, che erano i convogli e i muli dei rifornimenti, un uomo della milizia ferroviaria,
e le compagnie lavoratori.</p>

<p>Nella 1045ª compagnia lavoratori c'erano i due serbi, Ladislaus Nikolić e l'uomo che il
registro chiama Simboruir Mitasic. Un altro uomo di una compagnia lavoratori era nato a Vienna,
ed è morto qui nel maggio del 1916.</p>

<h4>E il 16° reggimento russo</h4>

<p>Un'ultima riga, che vale da sola. Alla voce reparto di Feodor Garasimovic c'è scritto
<i>Russ. 16. IR</i>: sedicesimo reggimento di fanteria <b>russo</b>. L'impiegato militare
austriaco che compilava il registro ha annotato con precisione il reparto nemico di un prigioniero
morto a mille chilometri dal proprio fronte, il 13 ottobre 1918, tre settimane prima della fine
di tutto.</p>

<h3>Anche loro erano i ragazzi del '99</h3>

<p>In Italia quell'espressione la conoscono tutti: la classe 1899, i diciottenni chiamati alle
armi dopo Caporetto, i più giovani mandati al fronte.</p>

<p><b>Sette dei centodiciotto uomini sepolti a Malè sono nati nel 1899.</b> Franz Belsak da Pettau
e Martin Vrzel e Karl Hammer da Marburg, tutti e tre stiriani. Johann Damoser dall'Alta Austria.
Georg Barla dall'Ungheria. Un ragazzo di cognome Matz dalla Slesia, di cui il registro non riporta
il nome. E Martin Gailberger, artigliere da montagna della Carinzia, morto il 20 ottobre 1918,
quindici giorni prima della fine della guerra.</p>

<p class="rilievo">Erano la stessa classe, gli stessi diciotto anni, la stessa guerra. Cambiava
solo da quale lato della montagna li avevano chiamati.</p>

<h3>Gli otto del Tonale</h3>

<p>Il 13 giugno 1918, alle tre e mezza del mattino, l'esercito austro-ungarico attacca il Passo
del Tonale. L'operazione si chiama <i>Unternehmen Lawine</i>, valanga. Due divisioni,
ventiquattro batterie di artiglieria, e il compito di attirare gli italiani lassù mentre il grosso
dell'offensiva si sarebbe mosso due giorni dopo sul Piave.</p>

<p>È l'ultima grande offensiva dell'impero, e sul Tonale si ferma il primo giorno stesso.</p>

<p>Malè era la retrovia di quel fronte. I feriti scendevano dal passo lungo la valle, verso gli
ospedali militari del paese. E il registro di Vienna, che non nomina mai l'operazione,
la racconta lo stesso attraverso le date:</p>

<ul class="caduti-evento">
  <li><b>14 giugno</b><span>Julius Hampl, moravo di Schmitz, quarantacinque anni.</span></li>
  <li><b>17 giugno</b><span>Josef Kraus, caporale del 1° reggimento artiglieria da montagna.</span></li>
  <li><b>17 giugno</b><span>Michel Fedorka, fante del <b>5° reggimento</b>, ungherese di Szatmár.</span></li>
  <li><b>17 giugno</b><span>Panko Genziuk, di un villaggio della Galizia.</span></li>
  <li><b>19 giugno</b><span>Josef Stein, cacciatore da campo, slesiano.</span></li>
  <li><b>19 giugno</b><span>Dimitri Koval, ventun anni, di Drozdowice presso Przemyśl.</span></li>
  <li><b>19 giugno</b><span>Peter Stanku, fante del <b>61° reggimento</b>, di Polanka presso Temesvár.</span></li>
  <li><b>20 giugno</b><span>Johann Szillagy, anche lui del <b>5°</b>, anche lui di Szatmár.</span></li>
</ul>

<p>Otto uomini in sette giorni, tutti nella finestra che segue l'attacco. Nessun documento lo
dichiara: <b>è un'inferenza costruita sulle date e sui reparti</b>, e sulle schede la trovate
scritta così, come probabile e non come certa.</p>

<p class="rilievo">C'è però una prova che regge da sola. Fedorka e Szillagy erano del 5°
reggimento e sono nati tutti e due a Szatmár. Stanku era del 61° ed è nato vicino a Temesvár.
<b>I luoghi di nascita corrispondono ai distretti di reclutamento dei loro reggimenti:</b> il
registro compilato a Malè e la struttura dell'esercito imperiale si confermano a vicenda, a
centosette anni di distanza.</p>

<p>Szatmár oggi si chiama Satu Mare, Temesvár si chiama Timișoara, e sono tutte e due in Romania.
Przemyśl è in Polonia. Quei tre uomini partirono da luoghi che hanno cambiato nome e nazione, per
morire in una valle che avrebbe cambiato nazione anche lei, due anni dopo di loro.</p>

<h3>Poi arrivò ottobre</h3>

<p>Nel 1914 muore un uomo solo, Johann Kükler, il 10 dicembre. Tre nel 1915, cinque nel 1916. Poi
il 1918, e i morti diventano centoquattro. <b>Quarantanove nel solo mese di ottobre</b>, le ultime
settimane prima della fine.</p>

<p>Malè era retrovia del fronte del Tonale e ospitava ospedali militari: qui arrivavano i feriti e
i malati dalla linea. In quelle stesse settimane l'influenza spagnola uccideva più soldati delle
granate, in tutti gli eserciti d'Europa. Il registro non riporta le cause di morte, e finché non
lo avremo accertato sui documenti sanitari non lo scriveremo come un fatto. Ma è certo che in
trenta giorni, in un paese di duemila anime, si scavarono quarantanove fosse.</p>

<h3>I quattro russi</h3>

<p>Fra i sepolti ci sono sei prigionieri di guerra: quattro russi e due serbi.</p>

<p>Ivan Kasimir Trimakus, nato a Kuwono nel 1887, muore il 17 ottobre 1918. Prokop Repenko, di
Poltawa, il giorno dopo. Vasyl Gapanov e Feodor Garasimovic il 13 dello stesso mese. <b>Quattro
uomini nemici, morti nella stessa settimana e nello stesso posto dei soldati che li
sorvegliavano</b>, e sepolti nello stesso campo.</p>

<p>I due serbi, Ladislaus Nikolić e un uomo che il registro chiama Simboruir Mitasic, erano
assegnati alla 1045ª compagnia lavoratori e riposano nel cimitero civile del paese. Erano stati
portati qui a lavorare, e qui sono rimasti.</p>

<h3>Perché li chiamiamo nostri</h3>

<p>Non c'è niente da rivendicare e niente da rimpiangere. Gli imperi finiscono, i confini si
spostano, e la storia non si giudica col metro di adesso.</p>

<p>C'è però una cosa che possiamo fare, ed è molto semplice: <b>tenere i nomi</b>. Perché per
centosette anni quei centodiciotto uomini sono stati un elenco chiuso in una scatola a mille
chilometri dalla terra che li ha accolti, e nessuno dei loro discendenti ha mai potuto sapere
dove fossero finiti.</p>

<p>Da oggi qualcuno in Stiria, in Ungheria o in Galizia può digitare un cognome e trovare una
risposta. <b>E centodiciotto tombe aspettano ancora che qualcun altro faccia lo stesso.</b></p>
