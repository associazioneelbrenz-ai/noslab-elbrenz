create or replace view public.v_memoria_persona_pubblica as
select
  p.id, p.slug,
  f.slug as fondo_slug, f.slug_breve as fondo_slug_breve, f.titolo as fondo_titolo, f.comune, f.valle,
  p.settore, p.numero, p.nome_completo, p.grado, p.reparto,
  p.data_morte_testo, p.data_morte, p.anno_nascita, p.luogo_nascita, p.regione_nascita,
  p.prigioniero_guerra, p.ignoto, p.note,
  e.slug as evento_slug, e.nome as evento_nome, p.evento_certezza,
  p.relazione_registrazione,
  p.relazione_registrazione is distinct from 'doppia_registrazione' as conta_nei_totali,
  p.nota_registrazione,
  a.settore as altra_settore, a.numero as altra_numero, a.slug as altra_slug,
  r.denominazione as reparto_denominazione, r.scioglimento as reparto_scioglimento,
  r.slug as reparto_slug, r.certezza as reparto_certezza,
  p.evento_motivazione
from memoria_persona p
join memoria_fondo f on f.id = p.fondo_id
left join memoria_evento e on e.id = p.evento_id
left join memoria_persona a on a.id = p.stessa_persona_di
left join memoria_reparto r on r.sigla = p.reparto
where f.stato = 'pubblicato';
alter view public.v_memoria_persona_pubblica set (security_invoker = true);
