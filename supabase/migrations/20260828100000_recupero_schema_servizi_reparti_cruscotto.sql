-- 1.1 servizio — registro dei servizi programmati che scrivono un battito
-- (brief "Il battito dei servizi", 28/8/2026). RLS attiva, NESSUNA policy:
-- solo le funzioni SECURITY DEFINER (registra_battito, cruscotto_servizi)
-- vi accedono, bypassando RLS come da proprietà. Nessun grant diretto.
create table if not exists public.servizio (
  nome                  text primary key,
  descrizione           text not null,
  cadenza_massima_ore   integer not null,
  attivo                boolean not null default true,
  creato_il             timestamptz not null default now()
);
alter table public.servizio enable row level security;
revoke all on public.servizio from anon, authenticated;

-- 1.2 servizio_battito — lo storico dei battiti. Stessa forma: RLS attiva,
-- nessuna policy, nessun grant diretto, accesso solo tramite le funzioni.
create table if not exists public.servizio_battito (
  id          bigint generated by default as identity primary key,
  servizio    text not null references public.servizio(nome) on delete cascade,
  esito       text not null check (esito in ('ok','errore','niente_da_fare')),
  dettaglio   jsonb,
  creato_il   timestamptz not null default now()
);
create index if not exists idx_battito_servizio_tempo on public.servizio_battito (servizio, creato_il desc);
alter table public.servizio_battito enable row level security;
revoke all on public.servizio_battito from anon, authenticated;

