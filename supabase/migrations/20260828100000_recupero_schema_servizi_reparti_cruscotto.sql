create or replace view public.v_coda_ascolto as
select a.id as audio_id, a.bucket, a.file_path, a.formato_audio, a.mime_originale,
       coalesce(a.durata_secondi, 0) as durata_secondi,
       a.parlata, a.comune_parlante, a.eta_parlante, a.sesso_parlante, a.nome_parlante,
       a.anonimo, a.voce_di_altri, a.consenso_parlante, a.registrato_il, a.luogo_registrazione, a.created_at,
       l.id as lemma_id, l.lemma, l.slug as lemma_slug, l.categoria_gramm, l.definizione, l.comune as lemma_comune,
       l.audio_id is not null as lemma_ha_gia_voce,
       row_number() over (order by a.created_at, a.id) as posizione,
       count(*) over () as totale,
       sum(coalesce(a.durata_secondi, 0)) over () as secondi_totali
from archivio_audio a
join dizionario_lemma l on l.id = a.lemma_id
where a.stato = 'in_attesa' and a.ascoltato_il is null;
alter view public.v_coda_ascolto set (security_invoker = true);
