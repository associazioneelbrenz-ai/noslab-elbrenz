create or replace view public.v_memoria_reparto_pubblico as
select r.sigla, r.slug, r.scioglimento, r.denominazione, r.arma, r.certezza, r.sigla_padre, r.note,
       count(p.id) as caduti,
       count(p.id) filter (where p.settore = 'militare') as caduti_militare,
       count(p.id) filter (where p.settore = 'civile') as caduti_civile
