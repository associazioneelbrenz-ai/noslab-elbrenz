<h3>Poi arrivò ottobre</h3>

<p>Nel 1914 muore un uomo solo, Johann Kükler, il 10 dicembre. Tre nel 1915, cinque nel 1916. Poi
il 1918, e i morti diventano centoquattro. <b>Quarantanove nel solo mese di ottobre</b>, le ultime
settimane prima della fine.</p>

<p>Malè era retrovia del fronte del Tonale e ospitava ospedali militari: qui arrivavano i feriti e
i malati dalla linea. In quelle stesse settimane l'influenza spagnola uccideva più soldati delle
granate, in tutti gli eserciti d'Europa. Il registro non riporta le cause di morte, e finché non
lo avremo accertato sui documenti sanitari non lo scriveremo come un fatto. Ma è certo che in
trenta giorni, in un paese di duemila anime, si scavarono quarantanove fosse.</p>

<h3>I quattro russi</h3>

<p>Fra i sepolti ci sono sei prigionieri di guerra: quattro russi e due serbi.</p>

<p>Ivan Kasimir Trimakus, nato a Kuwono nel 1887, muore il 17 ottobre 1918. Prokop Repenko, di
Poltawa, il giorno dopo. Vasyl Gapanov e Feodor Garasimovic il 13 dello stesso mese. <b>Quattro
uomini nemici, morti nella stessa settimana e nello stesso posto dei soldati che li
sorvegliavano</b>, e sepolti nello stesso campo.</p>

<p>I due serbi, Ladislaus Nikolić e un uomo che il registro chiama Simboruir Mitasic, erano
assegnati alla 1045ª compagnia lavoratori e riposano nel cimitero civile del paese. Erano stati
portati qui a lavorare, e qui sono rimasti.</p>

<h3>Perché li chiamiamo nostri</h3>

<p>Non c'è niente da rivendicare e niente da rimpiangere. Gli imperi finiscono, i confini si
spostano, e la storia non si giudica col metro di adesso.</p>

<p>C'è però una cosa che possiamo fare, ed è molto semplice: <b>tenere i nomi</b>. Perché per
centosette anni quei centodiciotto uomini sono stati un elenco chiuso in una scatola a mille
chilometri dalla terra che li ha accolti, e nessuno dei loro discendenti ha mai potuto sapere
dove fossero finiti.</p>

