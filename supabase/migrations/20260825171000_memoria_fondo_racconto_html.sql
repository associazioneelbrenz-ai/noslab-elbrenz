<h3>Anche loro erano i ragazzi del '99</h3>

<p>In Italia quell'espressione la conoscono tutti: la classe 1899, i diciottenni chiamati alle
armi dopo Caporetto, i più giovani mandati al fronte.</p>

<p><b>Sette dei centodiciotto uomini sepolti a Malè sono nati nel 1899.</b> Franz Belsak da Pettau
e Martin Vrzel e Karl Hammer da Marburg, tutti e tre stiriani. Johann Damoser dall'Alta Austria.
Georg Barla dall'Ungheria. Un ragazzo di cognome Matz dalla Slesia, di cui il registro non riporta
il nome. E Martin Gailberger, artigliere da montagna della Carinzia, morto il 20 ottobre 1918,
quindici giorni prima della fine della guerra.</p>

<p class="rilievo">Erano la stessa classe, gli stessi diciotto anni, la stessa guerra. Cambiava
